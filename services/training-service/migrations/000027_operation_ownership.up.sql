SELECT setval('training_operation_events_id_seq',COALESCE((SELECT max(id) FROM training_operation_events),1),EXISTS(SELECT 1 FROM training_operation_events));
CREATE TABLE training_tool_events (LIKE operation_events INCLUDING ALL);
INSERT INTO training_tool_events SELECT * FROM operation_events WHERE evidence->>'kind'='tool' AND evidence->>'actor'='assistant';
CREATE SEQUENCE training_tool_events_id_seq;
