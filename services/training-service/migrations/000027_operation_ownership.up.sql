CREATE TABLE training_operation_projection (LIKE session_operations INCLUDING ALL);
INSERT INTO training_operation_projection SELECT * FROM session_operations;
CREATE SEQUENCE training_operation_projection_id_seq;
ALTER TABLE training_operation_projection ALTER COLUMN id SET DEFAULT nextval('training_operation_projection_id_seq');
ALTER SEQUENCE training_operation_projection_id_seq OWNED BY training_operation_projection.id;
SELECT setval('training_operation_projection_id_seq',COALESCE((SELECT max(id) FROM training_operation_projection),1),EXISTS(SELECT 1 FROM training_operation_projection));
CREATE TABLE training_operation_audit_sessions (LIKE operation_audit_sessions INCLUDING ALL);
